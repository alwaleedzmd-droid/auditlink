def _norm(s: str) -> str:
    """Normalize Arabic strings for matching."""
    if s is None:
        return ""
    s = str(s).strip().lower()
    replacements = {'أ': 'ا', 'إ': 'ا', 'آ': 'ا', 'ى': 'ي', 'ة': 'ه', 'ؤ': 'و', 'ئ': 'ي'}
    for k, v in replacements.items():
        s = s.replace(k, v)
    return s


# المؤشر المفهرس (مطبَّع للمطابقة السريعة)
_INDEX = [(_norm(kw), pct) for kw, pct in PROFESSION_QUOTAS_RAW]


def get_quota(profession: str) -> int:
    """
    Return the HRSD Saudization quota (%) for the given profession.
    Matches by containment of normalized keywords; falls back to DEFAULT_QUOTA.
    Returns the HIGHEST matching quota if multiple keywords match.
    """
    if not profession:
        return DEFAULT_QUOTA

    norm_prof = _norm(profession)
    matched = [pct for kw, pct in _INDEX if kw and kw in norm_prof]
    return max(matched) if matched else DEFAULT_QUOTA


def get_quota_source(profession: str) -> tuple[int, str]:
    """Return (quota_pct, matched_keyword_or_default)."""
    if not profession:
        return DEFAULT_QUOTA, "افتراضي"
    norm_prof = _norm(profession)
    matches = [(kw, pct) for kw, pct in _INDEX if kw and kw in norm_prof]
    if not matches:
        return DEFAULT_QUOTA, "افتراضي (نطاقات)"
    best = max(matches, key=lambda x: x[1])
    return best[1], best[0]
